/* Live tuition estimator — mirrors mam_compute_application_price() exactly,
   reading the admin-editable values from MAM_CONFIG so it never drifts from
   what the server charges. Currency follows the page's currency toggle. */
(function () {
  'use strict';
  var $ = function (s, c) { return (c || document).querySelector(s); };
  var $$ = function (s, c) { return Array.prototype.slice.call((c || document).querySelectorAll(s)); };
  var calc = $('#calc'); if (!calc) return;

  var state = { prog: 'certified-musician', level: 'precert', mode: 'onsite', extra: 0, reg: true };

  function cfg() { return window.MAM_CONFIG || {}; }
  function levelPrices() { return cfg().levelPrices || { precert: 120, cert: 130, prediploma: 160, diploma: 180 }; }
  function compFee() { return cfg().compulsoryFeeUsd != null ? cfg().compulsoryFeeUsd : 120; }
  function regFee() { return cfg().registrationFeeUsd != null ? cfg().registrationFeeUsd : 5; }
  function onlinePct() { return cfg().onlineSurchargePct != null ? cfg().onlineSurchargePct : 20; }
  function flatPrice(p) { var pr = (cfg().pricing || {})[p]; return pr && pr.usd ? pr.usd : (p === 'crash' ? 70 : 60); }

  function activeCur() {
    // MAM_CCY.detect() is the site-wide source of truth — it reflects both auto
    // detection (e.g. a Kenyan visitor → KES, which has no toggle button) and any
    // explicit currency-btn click (main.js persists the choice to mam.currency).
    if (window.MAM_CCY) return MAM_CCY.detect();
    var b = $('.currency-toggle .currency-btn.active'); return b ? b.getAttribute('data-currency') : 'USD';
  }
  function fmt(usd) {
    if (window.MAM_CCY) return MAM_CCY.format(usd, activeCur());
    var cur = activeCur();
    var rates = (cfg().currency && cfg().currency.rates) || { USD: 1 };
    var sym = { USD: '$', NGN: '₦', GBP: '£', EUR: '€' }[cur] || (cur + ' ');
    return sym + Math.round(usd * (rates[cur] || 1)).toLocaleString('en-US');
  }

  function grandDisc() { return cfg().grandDiscountPct != null ? cfg().grandDiscountPct : 13; }
  function extraCap() { return state.prog === 'grand-musician' ? 6 : 4; }
  function isFlat() { return state.prog === 'crash' || state.prog === 'meta-order'; }

  // Returns the estimated total only (mirrors the server engine). No itemised
  // breakdown is surfaced — the pricing methodology isn't public.
  function compute() {
    var reg = state.reg ? regFee() : 0;
    if (isFlat()) return flatPrice(state.prog) + reg;
    var B = levelPrices()[state.level] || 0, sub, ex = state.extra;
    if (state.prog === 'grand-musician') {
      sub = (3 * B + 0.5 * B * ex) * (1 - grandDisc() / 100);
    } else {
      sub = B + (state.prog === 'certified-musician' ? compFee() : 0) + 0.5 * B * ex;
    }
    if (state.mode === 'online') sub = sub * (1 + onlinePct() / 100);
    return Math.round(sub) + reg;
  }

  function render() {
    // toggle level / extra fields for flat programmes
    var flat = isFlat();
    $('#calcLevelField').classList.toggle('calc-disabled', flat);
    $('#calcExtraField').classList.toggle('calc-disabled', flat);
    // clamp extra to the programme cap
    if (state.extra > extraCap()) state.extra = extraCap();
    $('#calcExtraVal').textContent = state.extra;
    $('#calcExtraHint').textContent = flat ? 'Not available'
      : (state.prog === 'standard' ? 'Beyond your primary course' : 'Beyond your primary + 4 compulsory');

    var total = compute();
    // Plain selection summary — NOT a breakdown of how the fee is computed.
    var names = { 'standard': 'Standard', 'certified-musician': 'Certified', 'grand-musician': 'Grand', 'crash': 'Crash', 'meta-order': 'MetaMusic Order' };
    var lvls = { precert: 'Pre-Certificate', cert: 'Certificate', prediploma: 'Pre-Diploma', diploma: 'Diploma' };
    var bits = [names[state.prog] || state.prog];
    if (!flat) bits.push(lvls[state.level] || state.level);
    bits.push(state.mode === 'online' ? 'Online' : 'Onsite');
    if (!flat && state.extra > 0) bits.push(state.extra + ' extra course' + (state.extra === 1 ? '' : 's'));
    if (state.reg) bits.push('registration included');
    $('#calcLines').innerHTML = bits.map(function (b) {
      return '<div class="calc-line"><span><i class="fa-solid fa-check" style="color:#34D399;margin-right:8px"></i>' + b + '</span></div>';
    }).join('');
    $('#calcTotal').textContent = fmt(total);

    // deep-link the Apply button
    var q = 'apply?pathway=' + encodeURIComponent(state.prog) + '&mode=' + encodeURIComponent(state.mode);
    if (!flat) q += '&level=' + encodeURIComponent(state.level);
    $('#calcApply').setAttribute('href', q);

    var fine = $('#calcFine');
    if (flat) fine.textContent = state.prog === 'crash'
      ? 'The Crash Programme is a flat fee with no levels.'
      : 'The MetaMusic Order is a standalone 12-week intensive.';
    else fine.textContent = 'Estimated total — confirmed at checkout. Registration covers your student file, ID card & a 30-minute MAM Auditer assessment.';
  }

  function bindSeg(id, key) {
    var wrap = $('#' + id); if (!wrap) return;
    wrap.addEventListener('click', function (e) {
      var b = e.target.closest('button[data-v]'); if (!b) return;
      state[key] = b.getAttribute('data-v');
      $$('button', wrap).forEach(function (x) { x.classList.toggle('on', x === b); });
      render();
    });
  }
  bindSeg('calcProg', 'prog');
  bindSeg('calcLevel', 'level');
  bindSeg('calcMode', 'mode');
  $('#calcPlus').addEventListener('click', function () { if (state.extra < extraCap()) { state.extra++; render(); } });
  $('#calcMinus').addEventListener('click', function () { if (state.extra > 0) { state.extra--; render(); } });
  $('#calcReg').addEventListener('change', function () { state.reg = this.checked; render(); });
  // Re-render when the currency toggle changes (main.js toggles .active on click).
  $$('.currency-toggle .currency-btn').forEach(function (b) { b.addEventListener('click', function () { setTimeout(render, 0); }); });
  // Re-render once live admin prices hydrate.
  document.addEventListener('mam:config', render);

  render();
})();
</script>
