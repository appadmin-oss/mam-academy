      <div class="hb-datepill"><i class="fa-solid fa-bookmark"></i> Effective 28 August 2025 &nbsp;·&nbsp; MAM Academy, Lagos</div>

      <p class="hb-p">This Handbook sets out the academic standards, personal responsibilities, and conduct expectations that apply to every student and instructor at MAM Academy. It should be read alongside the <a href="terms" class="hb-link">Terms of Service</a> and <a href="policies" class="hb-link">Class Policies</a>. Ignorance of these provisions is not a defence — all enrolled students and instructors are bound by them from their first session.</p>

      <!-- ── Part I ───────────────────────────────────────────── -->
      <section class="part-block" id="learning-model">
        <div class="part-eyebrow">Part I</div>
        <h2 class="part-heading">Learning Model &amp; Contact Sessions</h2>

        <h3 class="hb-sec">§1 — The Student-Led Guided Learning Model</h3>
        <p class="hb-p">MAM Academy operates a <strong>student-led guided learning model</strong>. Sessions are a space to demonstrate, deepen, and refine what you have already prepared — not to encounter material for the first time. Every student must undertake meaningful preparation before arriving at each session.</p>

        <div class="stat-row">
          <div class="stat-box"><div class="sn">70%</div><div class="sl">Student-led engagement in every session</div></div>
          <div class="stat-box"><div class="sn">30%</div><div class="sl">Instructor guidance, feedback &amp; facilitation</div></div>
        </div>

        <div class="hb-alert info"><i class="fa-solid fa-lightbulb"></i><div>Your first obligation is to your own study. MAM Academy equips and challenges you — it does not substitute for the independent work that happens between sessions.</div></div>

        <h3 class="hb-sec">§2 — Contact Session Types</h3>
        <p class="hb-p">Three types of session operate within every programme:</p>
        <ul class="hb-list">
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Weekly Contact Sessions</strong> — the primary learning session, student-led and instructor-facilitated</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Review Sessions</strong> — periodic assessments of progress across the current module</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Follow-Up / Clarification Sessions</strong> — 20–30 minute slots, booked by the student, for targeted questions after independent study. These are not full teaching sessions and require their own preparation</span></li>
        </ul>

        <h3 class="hb-sec">§3 — What Happens in a Contact Session</h3>
        <p class="hb-p">During a weekly contact session, students are expected to:</p>
        <ul class="hb-list">
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Demonstrate preparation on the week's material</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Lead discussion and practical exploration of the topic</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Present questions that require the instructor's expertise — not questions answerable by self-study</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Apply feedback in real time and document action points</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Maintain discipline: punctuality, attentiveness, and no use of mobile devices except for reference</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Communicate in advance (at least 24 hours) if unable to attend</span></li>
        </ul>

        <div class="hb-alert note"><i class="fa-solid fa-robot"></i><div><strong>AI Use Policy</strong> &mdash; Students may use AI tools for reference and exploration, but not as a substitute for independent study or practice. Work submitted or demonstrated in sessions must represent your own genuine effort. Presenting AI-generated output as personal work is a disciplinary matter.</div></div>

        <h3 class="hb-sec">§4 — Theory-Based Courses</h3>
        <p class="hb-p">Module completions for theory-based courses require written or recorded submissions. All work must be submitted within <strong>48 hours</strong> of the session in which it was set. Late submissions may be marked zero at the instructor's discretion.</p>
        <div class="stat-row">
          <div class="stat-box"><div class="sn">48h</div><div class="sl">Submission window for theory-based module work</div></div>
        </div>
      </section>

      <!-- ── Part II ──────────────────────────────────────────── -->
      <section class="part-block" id="student-responsibilities">
        <div class="part-eyebrow">Part II</div>
        <h2 class="part-heading">Student Responsibilities</h2>

        <p class="hb-p">Enrollment at MAM Academy carries obligations that go beyond attendance. Each student commits to the following from their first session:</p>

        <ul class="hb-list">
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Pre-session preparation</strong> — study materials, listen to references, and practise required exercises before every session</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Portal use</strong> — access the student portal regularly; check schedules, submitted work, results, and announcements</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Academic honesty</strong> — all submitted work must be your own; no plagiarism or misrepresentation of AI-assisted content</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Respectful conduct</strong> — treat instructors, classmates, and staff with courtesy at all times, in session and online</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Materials access</strong> — secure all required textbooks, instruments and digital tools before programme commencement, or within the first week</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Punctuality</strong> — arrive on time; late arrival of more than 10 minutes counts as an absence unless the instructor permits otherwise</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Communication</strong> — notify your instructor and the Academy at least 24 hours before any absence; extended absence requires written notice</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Feedback acceptance</strong> — receive instructor feedback with openness; challenge respectfully through proper channels, not in the moment of delivery</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Academy values</strong> — uphold the principles of discipline, honour and respect that define the MAM community</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span><strong>Financial obligations</strong> — maintain your fee account in good standing; contact the Academy promptly if you anticipate difficulty meeting a payment</span></li>
        </ul>
      </section>

      <!-- ── Part III ─────────────────────────────────────────── -->
      <section class="part-block" id="attendance">
        <div class="part-eyebrow">Part III</div>
        <h2 class="part-heading">Attendance</h2>

        <h3 class="hb-sec">§5 — Minimum Attendance Requirement</h3>

        <div class="stat-row">
          <div class="stat-box"><div class="sn">75%</div><div class="sl">Minimum attendance required per module cycle</div></div>
        </div>

        <p class="hb-p">Students must attend a minimum of <strong>75% of scheduled sessions</strong> within each module cycle. Falling below this threshold has the following consequences:</p>

        <ul class="hb-list">
          <li><i class="fa-solid fa-triangle-exclamation li-icon" style="color:#FB923C"></i><span>Ineligibility for module completion certification for that cycle</span></li>
          <li><i class="fa-solid fa-triangle-exclamation li-icon" style="color:#FB923C"></i><span>A formal attendance notice issued by the Academy</span></li>
          <li><i class="fa-solid fa-triangle-exclamation li-icon" style="color:#FB923C"></i><span>A mandatory review meeting before re-enrollment in the next cycle</span></li>
          <li><i class="fa-solid fa-triangle-exclamation li-icon" style="color:#FB923C"></i><span>Continued non-attendance may be treated as withdrawal, with fees forfeited per the Payments policy</span></li>
        </ul>

        <div class="hb-alert note"><i class="fa-solid fa-calendar-check"></i><div>Attendance is recorded by your instructor at the close of each session. QR self-check-in is available to supplement instructor records, but the instructor's mark is final.</div></div>
      </section>

      <!-- ── Part IV ──────────────────────────────────────────── -->
      <section class="part-block" id="assignments">
        <div class="part-eyebrow">Part IV</div>
        <h2 class="part-heading">Assignments &amp; Instruction Compliance</h2>

        <h3 class="hb-sec">§6 — Assignment Policy</h3>
        <p class="hb-p">All assignments set by instructors form part of your assessed programme work. Students are required to:</p>
        <ul class="hb-list">
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Submit by the deadline communicated at the time of setting</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Submit via the student portal unless the instructor specifies otherwise in writing</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Present work that reflects genuine personal effort — not copied, AI-generated, or reproduced from another student's submission</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Accept and action feedback; re-submission of revised work may be required at the instructor's discretion</span></li>
        </ul>

        <h3 class="hb-sec">§7 — Instruction Compliance</h3>
        <p class="hb-p">Students are required to follow all reasonable academic and administrative instructions issued by MAM Academy staff, including:</p>
        <ul class="hb-list">
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Instructions from instructors on session conduct, preparation requirements, and practice standards</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Administrative directives from the Academy regarding scheduling, documentation, and payment</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Corrections and guidance arising from module reviews or assessments</span></li>
        </ul>
        <p class="hb-p">Persistent non-compliance with reasonable instructions is a disciplinary matter and will be addressed through the Corrective Measures framework below.</p>
      </section>

      <!-- ── Part V ───────────────────────────────────────────── -->
      <section class="part-block" id="corrective-measures">
        <div class="part-eyebrow">Part V</div>
        <h2 class="part-heading">Corrective Measures</h2>

        <p class="hb-p">MAM Academy addresses conduct and compliance concerns through a structured, proportionate framework. Each instance is documented in the student's record.</p>

        <div class="disc-ladder">
          <div class="disc-rung d1">
            <span class="disc-badge">1st instance</span>
            <span><strong>Verbal advisory</strong> — a private conversation with the instructor or Academy coordinator. A written record is made. No formal penalty.</span>
          </div>
          <div class="disc-rung d2">
            <span class="disc-badge">2nd instance</span>
            <span><strong>Written warning + administrative fine of ₦500</strong> — a formal written notice is issued and the fine is posted to the student's account.</span>
          </div>
          <div class="disc-rung d3">
            <span class="disc-badge">3rd instance</span>
            <span><strong>Written warning + administrative fine of ₦1,000</strong> — a second formal notice is issued; a review meeting with Academy management may be required.</span>
          </div>
          <div class="disc-rung d4">
            <span class="disc-badge">4th+ instance</span>
            <span><strong>Fine of ₦3,000 and possible suspension</strong> — the Academy reserves the right to suspend the student pending a full conduct review. Continued enrolment is not guaranteed.</span>
          </div>
        </div>

        <div class="hb-alert warn"><i class="fa-solid fa-circle-exclamation"></i><div>Suspension removes a student from all scheduled sessions and freezes portal access for the duration of the review. Fees are not paused or refunded during a suspension period.</div></div>

        <p class="hb-p">Severe single instances — including but not limited to: physical aggression, theft, harassment, or deliberate submission of another student's work — may bypass the graduated ladder and result in immediate suspension or expulsion at the Academy's discretion, without refund.</p>
      </section>

      <!-- ── Part VI ──────────────────────────────────────────── -->
      <section class="part-block" id="payments">
        <div class="part-eyebrow">Part VI</div>
        <h2 class="part-heading">Payments &amp; Withdrawal</h2>

        <h3 class="hb-sec">§8 — Payment Policy</h3>
        <p class="hb-p">Programme fees must be paid in full — or the agreed instalment settled — before or on the first day of each programme cycle. Overdue accounts attract a late-payment notice; continued non-payment may result in suspension of portal access and exclusion from sessions until the account is settled.</p>
        <ul class="hb-list">
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>The booking fee is separate from tuition and is not credited against it</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Agreed payment plans must be honoured on the agreed schedule</span></li>
          <li><i class="fa-solid fa-circle-check li-icon" style="color:var(--gold-bright)"></i><span>Receipts and account statements are available at any time in the student portal under <strong>Payments</strong></span></li>
        </ul>

        <h3 class="hb-sec">§9 — Refund &amp; Withdrawal Policy</h3>
        <div class="hb-alert warn"><i class="fa-solid fa-triangle-exclamation"></i><div><strong>Fees are non-refundable once a programme has commenced.</strong> This applies to programme fees, registration fees, and the booking fee. See <a href="terms" class="hb-link">Terms of Service §3</a> for the full refund policy, including statutory rights that may apply to you.</div></div>
        <p class="hb-p">As an alternative to withdrawal, enrolled students may apply to pause their programme for up to four weeks per cycle. Approval is at the Academy's discretion and must be requested in writing before the pause period begins. Write to <a href="mailto:academy@mamcentre.org" class="hb-link">academy@mamcentre.org</a>.</p>
      </section>

      <!-- ── Part VII ─────────────────────────────────────────── -->
      <section class="part-block" id="instructor">
        <div class="part-eyebrow">Part VII</div>
        <h2 class="part-heading">Instructor Responsibilities</h2>

        <p class="hb-p">Instructors at MAM Academy are mentors, facilitators, and role models. By accepting an instructional appointment, each instructor commits to:</p>

        <ul class="hb-list">
