<script>
(function () {
  'use strict';
  var $ = function (id) { return document.getElementById(id); };
  // Transparent requirements (mirrors the server's mam_scholarship_requirements).
  var REQS = [
    'Aged 16–26', 'Some prior musical experience (not a complete beginner)',
    'Own — or have reliable access to — your instrument',
    'Available for weekly classes, including Saturdays',
    'Demonstrable financial need',
    'Alignment with MAM’s values & a heart to serve your community',
    'Committed to completing the programme'
  ];
  var reqEl = $('schReqs');
  if (reqEl) reqEl.innerHTML = REQS.map(function (r) { return '<li><i class="fa-solid fa-check" aria-hidden="true"></i><span>' + r + '</span></li>'; }).join('');

  var form = $('schForm'); if (!form) return;
  var REQUIRED = ['full_name', 'email', 'financial_need', 'musical_journey', 'values_alignment', 'community_impact'];
  function clearInvalid() {
    form.querySelectorAll('.invalid').forEach(function (e) { e.classList.remove('invalid'); });
  }
  form.addEventListener('submit', function (e) {
    e.preventDefault();
    clearInvalid();
    var fb = $('sch-feedback'); fb.className = 'sch-feedback';
    var body = {};
    REQUIRED.forEach(function (n) { body[n] = (form.querySelector('[name="' + n + '"]').value || '').trim(); });
    body.age_band = form.querySelector('[name="age_band"]').value || '';
    body.experience = form.querySelector('[name="experience"]').value || '';
    body.commitment_ack = $('sch-commit').checked;

    // Light client-side check (server is authoritative).
    var bad = [];
    if (body.full_name.length < 2) bad.push('sch-name');
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(body.email)) bad.push('sch-email');
    [['financial_need','sch-fin'],['musical_journey','sch-journey'],['values_alignment','sch-values'],['community_impact','sch-impact']].forEach(function (p) {
      if (body[p[0]].length < 10) bad.push(p[1]);
    });
    if (!body.commitment_ack) { $('sch-consent-wrap').classList.add('invalid'); bad.push('sch-commit'); }
    if (bad.length) {
      bad.forEach(function (id) { var el = $(id); if (el && el.closest('.sch-field')) el.closest('.sch-field').classList.add('invalid'); });
      fb.className = 'sch-feedback err'; fb.textContent = 'Please complete the highlighted fields (a sentence or two each) and confirm your commitment.';
      var first = $(bad[0]); if (first && first.focus) first.focus();
      return;
    }
    if (!window.MAM_API) { fb.className = 'sch-feedback err'; fb.textContent = 'Something went wrong loading the form. Please reload and try again.'; return; }

    var btn = $('sch-submit'); var orig = btn.innerHTML; btn.disabled = true; btn.innerHTML = '<i class="fa-solid fa-circle-notch fa-spin"></i> Submitting…';
    window.MAM_API.request('scholarship/apply', { method: 'POST', body: body })
      .then(function (r) {
        var ref = (r && r.reference) || '';
        $('schGrid').innerHTML = '<div class="sch-success">'
          + '<div class="ic"><i class="fa-solid fa-hand-holding-heart"></i></div>'
          + '<h2>Thank you — your application is in</h2>'
          + '<p style="color:var(--text-soft);line-height:1.65">We’re honoured you applied to the MAM Scholars Initiative. Our committee reviews every application holistically; we’ll be in touch by email.</p>'
          + (ref ? '<div class="sch-ref">' + ref.replace(/[^A-Za-z0-9-]/g, '') + '</div><p style="color:var(--text-muted);font-size:.82rem">Keep this reference to check your status.</p>' : '')
          + '<div style="margin-top:18px"><a class="btn btn-secondary" href="/"><i class="fa-solid fa-house"></i> Back to home</a></div>'
          + '</div>';
        window.scrollTo({ top: 0, behavior: 'smooth' });
      })
      .catch(function (err) {
        btn.disabled = false; btn.innerHTML = orig;
        var fields = (err && err.body && err.body.fields) || [];
        if (fields.length) fields.forEach(function (n) { var el = form.querySelector('[name="' + n + '"]'); if (el && el.closest('.sch-field')) el.closest('.sch-field').classList.add('invalid'); });
        fb.className = 'sch-feedback err'; fb.textContent = 'We couldn’t submit that. Please check the highlighted fields and try again.';
      });
  });
})();
</script>
